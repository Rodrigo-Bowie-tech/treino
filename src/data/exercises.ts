export const EXERCISES: Exercise[] = [...WARMUP, ...FASCIITIS, ...BICEPS, ...TRICEPS, ...SHOULDERS, ...FOREARMS, ...COOLDOWN];

const BY_ID = new Map(EXERCISES.map((e) => [e.id, e]));

export function getExercise(id: string): Exercise {
  const ex = BY_ID.get(id);
  if (!ex) throw new Error(`Exercício desconhecido: ${id}`);
  return ex;
}

export function findExercise(id: string): Exercise | undefined {
  return BY_ID.get(id);
}

export function byCategory(category: Category): Exercise[] {
  return EXERCISES.filter((e) => e.category === category);
}

