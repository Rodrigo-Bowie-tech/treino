/** "Halteres + Banco"; sem equipamento = undefined. */
export function equipmentLabel(ex: Exercise): string | undefined {
  return ex.equipment?.length ? ex.equipment.map((e) => EQUIPMENT_LABELS[e]).join(' + ') : undefined;
}

